// 高低差: A 台 (1.2m)、A ヘブン (2.4m)、渡り廊下と B 窓 (2.0m)、B 台 (1.6m)。高い所からは飛び降りられる

const A = (name, x0, z0, x1, z1, opts = {}) => ({ name, x0, z0, x1, z1, ...opts });
/** 斜めのエリア。pts は多角形の頂点 [[x,z],...] */
const P = (name, pts, opts = {}) => ({
  name, poly: pts, ...opts,
  x0: Math.min(...pts.map((p) => p[0])), z0: Math.min(...pts.map((p) => p[1])),
  x1: Math.max(...pts.map((p) => p[0])), z1: Math.max(...pts.map((p) => p[1])),
});

